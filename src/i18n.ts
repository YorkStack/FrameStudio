const translations: Record<string,string> = {...Object.fromEntries(Object.entries(german).map(([key,value])=>[value,english[key as keyof typeof english]])),...literals,...errorEnglish};
export function t(value: string): string { return language === "en" ? translations[value] || value : value; }
export const de = new Proxy(german, {get(target,key: keyof typeof german) { return language === "en" ? english[key] : target[key]; }}) as Record<keyof typeof german,string>;
export function localizedRecord<T extends Record<string,string>>(record:T):T { return new Proxy(record,{get(target,key:string){return t(target[key]);}}); }
export const statuses = localizedRecord(statusGerman);
export const costStatuses: Record<string,string> = new Proxy(costKeys,{get(target,key:keyof typeof costKeys){return de[target[key] as keyof typeof de];}});

export function formatText(template:string, ...values:(string|number)[]) { return t(template).replace(/\{(\d+)\}/g,(_,n)=>String(values[Number(n)] ?? "")); }

export function translateError(value: string): string {
  if (language !== "en") return value;
  if (translations[value]) return translations[value];
  // Translate known diagnostics only; retain provider codes and variable details verbatim.
  let result = value;
  for (const [source, target] of Object.entries(errorEnglish).sort((a,b)=>b[0].length-a[0].length)) {
    if (source.length > 20 && !source.includes("{")) result = result.replaceAll(source, target);
  }
  return result;
}

export function styleName(style:Record<string,any>) { return /^00000000-0000-4000-8000-/.test(style.id) && (style.version || 1) === 1 ? t(style.name) : style.name; }
